import asyncio,time,json
from playwright.async_api import async_playwright
async def main():
 async with async_playwright() as p:
  b=await p.chromium.launch(executable_path='/usr/bin/google-chrome',headless=True,args=['--no-sandbox'])
  page=await b.new_page(viewport={'width':1280,'height':900})
  await page.goto('http://localhost:4200/account',wait_until='networkidle')
  await page.get_by_role('button',name='Create account',exact=True).first.click()
  await page.locator('input[name=name]').fill('QA Account')
  email=f'qa-{int(time.time())}@example.com'
  await page.locator('input[name=email]').fill(email)
  await page.locator('input[name=password]').fill('Test-Only-Password-492!')
  await page.get_by_role('button',name='Create account',exact=True).last.click()
  await page.get_by_role('heading',name='Hello, QA Account.').wait_for()
  await page.goto('http://localhost:4200/shop/digital/daily-wellness-planner',wait_until='networkidle')
  await page.get_by_role('button',name='Buy Now — preview checkout').click()
  await page.get_by_role('link',name='Continue to demo checkout',exact=True).click()
  await page.locator('input[name=name]').fill('QA Account')
  await page.locator('input[name=email]').fill(email)
  await page.locator('input[type=checkbox]').check()
  await page.get_by_role('button',name='Place demo order — no payment').click()
  await page.wait_for_url('**/order/**')
  order=await page.locator('.order-id').inner_text()
  await page.goto('http://localhost:4200/account',wait_until='networkidle')
  await page.get_by_text(order,exact=True).wait_for()
  await page.get_by_role('button',name='Sign out',exact=True).click()
  await page.get_by_role('button',name='Sign in',exact=True).first.wait_for()
  await page.locator('input[name=email]').fill(email)
  await page.locator('input[name=password]').fill('Test-Only-Password-492!')
  await page.get_by_role('button',name='Sign in',exact=True).last.click()
  await page.get_by_role('heading',name='Hello, QA Account.').wait_for()
  await page.goto('http://localhost:4200',wait_until='networkidle')
  await page.locator('#email-community').fill(email)
  await page.locator('.newsletter input[type=checkbox]').check()
  await page.get_by_role('button',name='Join Nourish & Heal',exact=False).click()
  await page.get_by_text('You’re on the list. Thank you for joining.').wait_for()
  print(json.dumps({'signup':'passed','signout':'passed','email_signin':'passed','protected_order_history':'passed','newsletter':'persisted','google':'configured; external interactive flow not tested'},indent=2))
  await b.close()
asyncio.run(main())
